"""Self-contained schema inference for TFCI CSVs (no bootstrap import)."""
import csv, re
from pathlib import Path

PK_MAP = {
    "jurisdictions": ["jurisdiction_slug"],
    "sectors": ["sector_slug"],
    "sector_scores": ["jurisdiction_slug", "sector_slug"],
    "ledger_coverage": ["jurisdiction_slug", "sector_slug"],
    "projects": ["project_id"],
    "ledger_events": ["event_id"],
    "veto_ledger": ["event_id"],
    "evidence_sources": ["source_id"],
    "score_history": ["snapshot_date", "jurisdiction_slug", "sector_slug"],
    "staging_events": ["staging_id"],
}

def _infer(col, values):
    sample = [v for v in values if v not in ("", None)]
    if not sample:
        return "TEXT"
    if all(re.fullmatch(r"-?\d+", v) for v in sample):
        return "BIGINT" if any(abs(int(v)) > 2**31 for v in sample) else "INTEGER"
    if all(re.fullmatch(r"-?\d+\.\d+", v) for v in sample):
        return "NUMERIC"
    if all(v.lower() in ("true", "false") for v in sample):
        return "BOOLEAN"
    if all(re.fullmatch(r"\d{4}-\d{2}-\d{2}", v) for v in sample):
        return "DATE"
    return "TEXT"

def build_schema(data_dir):
    data = Path(data_dir)
    lines = ["-- AUTO-GENERATED by schema_gen.py from data/*.csv headers", ""]
    mapping = {}
    for p in sorted(data.glob("*.csv")):
        tbl = p.stem
        with open(p, newline="", encoding="utf-8-sig") as f:
            rdr = csv.reader(f)
            try:
                header = next(rdr)
            except StopIteration:
                continue
            rows = []
            for r in rdr:
                rows.append(r)
                if len(rows) >= 200:
                    break
        hdr_l = [h.strip().lower() for h in header]
        cols = []
        for i, col in enumerate(header):
            col = (col or "col_%d" % i).strip()
            vals = [r[i] if i < len(r) else "" for r in rows]
            cols.append('  "%s" %s' % (re.sub(r"\W+", "_", col.lower()), _infer(col, vals)))
        pk = PK_MAP.get(tbl)
        if pk and all(c.lower() in hdr_l for c in pk):
            cols.append("  PRIMARY KEY (%s)" % ", ".join('"%s"' % c for c in pk))
        lines.append("DROP TABLE IF EXISTS %s CASCADE;" % tbl)
        lines.append("CREATE TABLE %s (" % tbl)
        lines.append(",\n".join(cols))
        lines.append(");")
        lines.append("")
        mapping[tbl] = p
    return "\n".join(lines), mapping
